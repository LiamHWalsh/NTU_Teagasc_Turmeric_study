# Section: Exact small-N global test (CLR delta)
compute_clr_matrix <- function(feature_matrix, pseudocount = 1e-06) {
  feature_matrix <- as.matrix(feature_matrix)
  storage.mode(feature_matrix) <- "numeric"

  if (any(is.na(feature_matrix))) {
    stop("Feature matrix contains missing values; cannot compute CLR.")
  }

  feature_matrix <- feature_matrix + pseudocount
  sample_sums <- colSums(feature_matrix)
  sample_sums[sample_sums == 0] <- 1
  rel_abund <- sweep(feature_matrix, 2, sample_sums, "/")

  log_rel <- log(rel_abund)
  clr <- apply(log_rel, 2, function(x) x - mean(x))

  if (is.vector(clr)) {
    clr <- matrix(clr, nrow = nrow(feature_matrix))
  }

  rownames(clr) <- rownames(feature_matrix)
  colnames(clr) <- colnames(feature_matrix)
  clr
}

build_delta_matrix <- function(clr_matrix, metadata) {
  md <- metadata %>%
    filter(
      turmeric_group %in% c("Control", "Treatment"),
      timepoint %in% c("Baseline", "6_months")
    ) %>%
    mutate(turmeric_group = as.character(turmeric_group))

  pairs <- md %>%
    count(block_number, turmeric_group, timepoint, name = "n") %>%
    tidyr::pivot_wider(names_from = timepoint, values_from = n, values_fill = 0) %>%
    filter(Baseline == 1, `6_months` == 1) %>%
    select(block_number, turmeric_group) %>%
    arrange(block_number)

  if (nrow(pairs) == 0) {
    stop("No complete baseline/6-month participant pairs available.")
  }

  delta <- t(vapply(seq_len(nrow(pairs)), function(i) {
    participant_id <- pairs$block_number[i]
    s0 <- md$sample_id[md$block_number == participant_id & md$timepoint == "Baseline"][1]
    s6 <- md$sample_id[md$block_number == participant_id & md$timepoint == "6_months"][1]

    if (!(s0 %in% colnames(clr_matrix)) || !(s6 %in% colnames(clr_matrix))) {
      stop(glue::glue("Missing CLR columns for participant {participant_id}."))
    }

    clr_matrix[, s6] - clr_matrix[, s0]
  }, numeric(nrow(clr_matrix))))

  colnames(delta) <- rownames(clr_matrix)
  rownames(delta) <- pairs$block_number

  list(delta = delta, pairs = pairs)
}

pseudoF_oneway <- function(X, group_factor) {
  g <- factor(group_factor)
  n <- nrow(X)
  k <- nlevels(g)
  if (k < 2) return(c(F = NA_real_, R2 = NA_real_))

  grand <- colMeans(X)
  ss_total <- sum(rowSums((X - matrix(grand, n, ncol(X), byrow = TRUE))^2))

  ss_within <- 0
  for (lev in levels(g)) {
    Xg <- X[g == lev, , drop = FALSE]
    cg <- colMeans(Xg)
    ss_within <- ss_within + sum(rowSums((Xg - matrix(cg, nrow(Xg), ncol(X), byrow = TRUE))^2))
  }

  ss_between <- ss_total - ss_within
  df_between <- k - 1
  df_within <- n - k

  if (df_within <= 0 || ss_within <= 0 || ss_total <= 0) {
    return(c(F = NA_real_, R2 = NA_real_))
  }

  F_value <- (ss_between / df_between) / (ss_within / df_within)
  R2_value <- ss_between / ss_total
  c(F = F_value, R2 = R2_value)
}

run_exact_clr_delta_global <- function(abundance_df, metadata, profile_type) {
  feature_col <- colnames(abundance_df)[1]
  sample_ids <- colnames(abundance_df)[-1]
  keep_samples <- intersect(sample_ids, metadata$sample_id)

  if (length(keep_samples) == 0) {
    stop(glue::glue("No overlapping samples for {profile_type} CLR-delta analysis."))
  }

  feature_matrix <- as.matrix(abundance_df[, keep_samples, drop = FALSE])
  rownames(feature_matrix) <- abundance_df[[feature_col]]
  clr_matrix <- compute_clr_matrix(feature_matrix)

  delta_obj <- build_delta_matrix(clr_matrix, metadata)
  X <- delta_obj$delta
  pairs <- delta_obj$pairs
  group <- pairs$turmeric_group

  obs <- pseudoF_oneway(X, group)

  n <- length(group)
  n_tx <- sum(group == "Treatment")
  combos <- combn(n, n_tx)
  F_perm <- numeric(ncol(combos))

  for (i in seq_len(ncol(combos))) {
    idx <- combos[, i]
    g <- rep("Control", n)
    g[idx] <- "Treatment"
    F_perm[i] <- pseudoF_oneway(X, g)["F"]
  }

  p_exact <- mean(F_perm >= obs["F"], na.rm = TRUE)

  data.frame(
    profile = profile_type,
    n_pairs = nrow(pairs),
    n_treatment = sum(group == "Treatment"),
    n_control = sum(group == "Control"),
    pseudoF = as.numeric(obs["F"]),

prepare_beta_results <- function(distance_matrix_df, metadata) {
  
  cat("Preparing beta diversity results...\n")
  cat("Distance matrix samples:", nrow(distance_matrix_df), "\n")
  cat("Metadata samples:", nrow(metadata), "\n")
  
  # Get sample IDs from distance matrix
  dist_sample_ids <- distance_matrix_df$sample_id
  
  # Filter metadata to only include samples in distance matrix
  metadata_filtered <- metadata %>%
    filter(sample_id %in% dist_sample_ids)
  
  cat("Filtered metadata samples:", nrow(metadata_filtered), "\n")
  
  # Filter distance matrix to only include samples in metadata
  common_samples <- intersect(dist_sample_ids, metadata_filtered$sample_id)
  
  cat("Common samples:", length(common_samples), "\n")
  
  # Subset distance matrix to common samples
  distance_matrix_filtered <- distance_matrix_df %>%
    filter(sample_id %in% common_samples) %>%
    column_to_rownames("sample_id") %>%
    select(all_of(common_samples))
  
  # Convert to dist object
  dist_matrix <- as.dist(distance_matrix_filtered)
  
  # Order metadata to match distance matrix
  metadata_ordered <- metadata_filtered %>%
    filter(sample_id %in% common_samples) %>%
    arrange(match(sample_id, common_samples))
  
  # Verify matching
  cat("Distance matrix size:", attr(dist_matrix, "Size"), "\n")
  cat("Metadata rows:", nrow(metadata_ordered), "\n")
  
  if (attr(dist_matrix, "Size") != nrow(metadata_ordered)) {
    stop("Sample size mismatch between distance matrix and metadata!")
  }
  
  # Verify order matches
  dist_labels <- labels(dist_matrix)
  if (!all(dist_labels == metadata_ordered$sample_id)) {
    stop("Sample order mismatch between distance matrix and metadata!")
  }
  
  cat("Ã¢Å“â€¦ Successfully prepared beta results\n\n")
  
  return(list(
    distance_matrix = dist_matrix,
    metadata = metadata_ordered
  ))
}

